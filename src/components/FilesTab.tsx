import React, { useState, useMemo } from 'react';
import { ItemRecord, TriggerType, OpenMode, AdminUser, DesignConfig, api } from '../lib/api';
import { 
  FileText, Link2, Plus, Search, Edit2, Trash2, ExternalLink, 
  Sparkles, Check, X, ShieldAlert, ArrowRight, Play, FileUp, Globe, Smartphone,
  Copy, Hash, ChevronDown, ChevronUp, Share2, Upload, AlertTriangle, Paperclip, Loader2,
  Clock, Calendar, RefreshCw, Image, Video, Music, CheckCircle2
} from 'lucide-react';

interface FilesTabProps {
  items: ItemRecord[];
  currentUser: AdminUser;
  botUsername?: string;
  design?: DesignConfig;
  onRefresh: () => void;
  onSimulate?: (trigger: string) => void;
}

interface MultiFileEntry {
  id: string;
  file?: File;
  name: string;
  size: number;
  type: 'document' | 'photo' | 'video' | 'audio';
  telegramFileId?: string;
  uploadedFileId?: string;
  previewUrl?: string;
}

const FilesTabComponent: React.FC<FilesTabProps> = ({
  items,
  currentUser,
  botUsername,
  design,
  onRefresh,
  onSimulate
}) => {
  const [filter, setFilter] = useState<'all' | 'file' | 'link' | 'temporary' | 'permanent'>('all');
  const [search, setSearch] = useState('');

  // Modals state
  const [modalMode, setModalMode] = useState<'none' | 'add' | 'edit'>('none');
  const [selectedItem, setSelectedItem] = useState<ItemRecord | null>(null);
  const [deleteConfirmId, setDeleteConfirmId] = useState<string | null>(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);

  // Streamlined Form State
  const [itemType, setItemType] = useState<'file' | 'link'>('file');
  const [autoGeneratedId, setAutoGeneratedId] = useState('');
  const [name, setName] = useState('');
  const [rawKeyword, setRawKeyword] = useState('');
  const [triggerType, setTriggerType] = useState<TriggerType>('hashtag');
  const [caption, setCaption] = useState('Here is your requested file!');
  const [buttonText, setButtonText] = useState('📥 Download File');
  const [url, setUrl] = useState('');
  const [openMode, setOpenMode] = useState<OpenMode>('browser');
  const [retentionType, setRetentionType] = useState<'permanent' | 'temporary'>('permanent');
  const [retentionDays, setRetentionDays] = useState<number>(7);

  // Multi-File upload list
  const [selectedFiles, setSelectedFiles] = useState<MultiFileEntry[]>([]);
  const [uploading, setUploading] = useState(false);
  const [uploadStatus, setUploadStatus] = useState<string | null>(null);

  // Quick Action feedback
  const [copiedLinkItemId, setCopiedLinkItemId] = useState<string | null>(null);
  const [copiedTag, setCopiedTag] = useState<string | null>(null);

  const canAddFile = currentUser.role === 'owner' || currentUser.permissions.files_add;
  const canAddLink = currentUser.role === 'owner' || currentUser.permissions.links_add;
  const canEdit = currentUser.role === 'owner' || currentUser.permissions.files_edit || currentUser.permissions.links_edit;
  const canDelete = currentUser.role === 'owner' || currentUser.permissions.files_delete || currentUser.permissions.links_delete;

  const generateRandomId = (type: 'file' | 'link') => {
    const prefix = type === 'file' ? 'f_' : 'l_';
    const rand = Math.random().toString(36).substring(2, 8);
    return `${prefix}${rand}`;
  };

  const copyDeepLink = async (itemId: string, link: string) => {
    try {
      await navigator.clipboard.writeText(link);
      setCopiedLinkItemId(itemId);
      setTimeout(() => setCopiedLinkItemId((prev) => (prev === itemId ? null : prev)), 2500);
    } catch (err) {
      console.warn('Clipboard copy error:', err);
    }
  };

  const copySingleTag = async (tag: string) => {
    try {
      await navigator.clipboard.writeText(tag);
      setCopiedTag(tag);
      setTimeout(() => setCopiedTag((prev) => (prev === tag ? null : prev)), 2000);
    } catch (err) {
      console.warn('Clipboard copy error:', err);
    }
  };

  const openAddModal = (initialType: 'file' | 'link' = 'file') => {
    setError(null);
    setSelectedItem(null);
    setItemType(initialType);
    const newId = generateRandomId(initialType);
    setAutoGeneratedId(newId);
    setName('');
    setRawKeyword('');
    setTriggerType('hashtag');
    setCaption(initialType === 'file' ? 'Here is your requested file!' : '🔗 Here is your requested link:');
    setButtonText(initialType === 'file' ? '📥 Download File' : '🌐 Open Link');
    setUrl('');
    setOpenMode('browser');
    setRetentionType('permanent');
    setRetentionDays(7);
    setSelectedFiles([]);
    setUploadStatus(null);
    setModalMode('add');
  };

  const openEditModal = (item: ItemRecord) => {
    setError(null);
    setSelectedItem(item);
    setItemType(item.type);
    setAutoGeneratedId(item.id);
    setName(item.name);
    setRawKeyword(item.rawKeyword);
    setTriggerType(item.triggerType);
    setCaption(item.caption || (item.type === 'file' ? 'Here is your requested file!' : '🔗 Here is your requested link:'));
    setButtonText(item.buttonText || (item.type === 'file' ? '📥 Download File' : item.openMode === 'webapp' ? '📱 Launch App' : '🌐 Open Link'));
    setUrl(item.url || '');
    setOpenMode(item.openMode || 'browser');
    setRetentionType(item.retentionType || 'permanent');
    setRetentionDays(item.retentionDays || 7);
    
    // Existing file preview
    if (item.type === 'file') {
      setSelectedFiles([
        {
          id: item.uploadedFileId || item.telegramFileId || item.id,
          name: item.fileName || item.name,
          size: item.fileSize || 0,
          type: item.fileType || 'document',
          telegramFileId: item.telegramFileId,
          uploadedFileId: item.uploadedFileId
        }
      ]);
    } else {
      setSelectedFiles([]);
    }

    setUploadStatus(null);
    setModalMode('edit');
  };

  // Multi-File selection handler from gallery/phone files
  const handleMultiFileSelect = (e: React.ChangeEvent<HTMLInputElement>) => {
    const fileList = e.target.files;
    if (!fileList || fileList.length === 0) return;

    const newEntries: MultiFileEntry[] = [];

    for (let i = 0; i < fileList.length; i++) {
      const file = fileList[i];
      const mime = file.type || '';
      const lower = file.name.toLowerCase();

      let fType: 'document' | 'photo' | 'video' | 'audio' = 'document';
      if (mime.startsWith('image/') || /\.(jpg|jpeg|png|webp|gif)$/i.test(lower)) fType = 'photo';
      else if (mime.startsWith('video/') || /\.(mp4|mkv|mov|avi|webm)$/i.test(lower)) fType = 'video';
      else if (mime.startsWith('audio/') || /\.(mp3|wav|ogg|m4a|aac)$/i.test(lower)) fType = 'audio';
      else fType = 'document';

      let previewUrl: string | undefined = undefined;
      if (fType === 'photo') {
        try {
          previewUrl = URL.createObjectURL(file);
        } catch {}
      }

      newEntries.push({
        id: `f_${Date.now()}_${i}_${Math.random().toString(36).substring(2, 6)}`,
        file,
        name: file.name,
        size: file.size,
        type: fType,
        previewUrl
      });
    }

    setSelectedFiles((prev) => {
      const combined = [...prev, ...newEntries];
      // Auto-populate File Name and Trigger keyword if empty
      if (!name.trim() && combined[0]) {
        const cleanBase = combined[0].name.replace(/\.[^/.]+$/, '');
        setName(cleanBase);
        if (!rawKeyword.trim()) {
          const autoKey = cleanBase.toLowerCase().replace(/[^a-z0-9]/g, '').slice(0, 12);
          setRawKeyword(autoKey);
        }
      }
      return combined;
    });

    e.target.value = '';
  };

  // Remove individual file from multi-file selection
  const handleRemoveFile = (idToRemove: string) => {
    setSelectedFiles((prev) => prev.filter((f) => f.id !== idToRemove));
  };

  const previewTrigger = () => {
    const clean = rawKeyword.replace(/^[#/]+/, '').trim() || 'keyword';
    if (triggerType === 'hashtag') return `#${clean}`;
    if (triggerType === 'slash') return `/${clean}`;
    return clean;
  };

  const handleSave = async (e: React.FormEvent) => {
    e.preventDefault();
    if (!name.trim() || !rawKeyword.trim()) {
      setError('File/Link Name and Trigger keyword are required');
      return;
    }

    if (itemType === 'link' && !url.trim()) {
      setError('Valid Target URL is required for link');
      return;
    }

    if (itemType === 'file' && selectedFiles.length === 0 && !selectedItem) {
      setError('Please upload at least one file from Gallery / Device');
      return;
    }

    setLoading(true);
    setError(null);

    const cleanKeyword = rawKeyword.replace(/^[#/]+/, '').trim();
    const primaryTrigger =
      triggerType === 'hashtag'
        ? `#${cleanKeyword}`
        : triggerType === 'slash'
        ? `/${cleanKeyword}`
        : cleanKeyword;

    try {
      if (selectedItem) {
        // Edit existing item
        let uploadedFileId = selectedItem.uploadedFileId;
        let telegramFileId = selectedItem.telegramFileId;
        let fileName = selectedItem.fileName || name;
        let fileType = selectedItem.fileType || 'document';
        let fileSize = selectedItem.fileSize;

        // If a new file was uploaded to replace it
        const pendingFile = selectedFiles.find((f) => f.file);
        if (pendingFile && pendingFile.file) {
          const fd = new FormData();
          fd.append('file', pendingFile.file);
          fd.append('fileName', pendingFile.name);
          fd.append('fileType', pendingFile.type);
          const res = await api.uploadFile(fd);
          uploadedFileId = res.uploadedFileId || res.fileId;
          telegramFileId = res.fileId;
          fileName = pendingFile.name;
          fileType = pendingFile.type;
          fileSize = pendingFile.size;
        }

        await api.updateItem(selectedItem.id, {
          name: name.trim(),
          rawKeyword: cleanKeyword,
          triggerType,
          triggers: [primaryTrigger],
          caption: caption.trim() || undefined,
          telegramFileId: telegramFileId || undefined,
          uploadedFileId: uploadedFileId || undefined,
          fileType,
          fileName,
          fileSize,
          url: itemType === 'link' ? url.trim() : undefined,
          openMode: itemType === 'link' ? openMode : undefined,
          buttonText: buttonText.trim() || undefined,
          replyMessage: caption.trim() || undefined,
          retentionType: itemType === 'file' ? retentionType : undefined,
          retentionDays: itemType === 'file' && retentionType === 'temporary' ? retentionDays : undefined
        });
      } else {
        // Create new item(s) - Supports Multi-File uploads!
        if (itemType === 'file') {
          // If multiple files selected, save all of them
          for (let i = 0; i < selectedFiles.length; i++) {
            const entry = selectedFiles[i];
            let uploadedFileId: string | undefined = entry.uploadedFileId;
            let telegramFileId: string | undefined = entry.telegramFileId;

            if (entry.file) {
              setUploadStatus(`Uploading ${entry.name} (${i + 1}/${selectedFiles.length})...`);
              const fd = new FormData();
              fd.append('file', entry.file);
              fd.append('fileName', entry.name);
              fd.append('fileType', entry.type);
              const res = await api.uploadFile(fd);
              uploadedFileId = res.uploadedFileId || res.fileId;
              telegramFileId = res.fileId;
            }

            const itemName = selectedFiles.length > 1
              ? `${name.trim()} (${i + 1})`
              : name.trim();

            const itemKeyword = selectedFiles.length > 1 && i > 0
              ? `${cleanKeyword}${i + 1}`
              : cleanKeyword;

            const itemTrigger = triggerType === 'hashtag'
              ? `#${itemKeyword}`
              : triggerType === 'slash'
              ? `/${itemKeyword}`
              : itemKeyword;

            const targetId = i === 0 ? autoGeneratedId : generateRandomId('file');

            await api.createItem({
              id: targetId,
              name: itemName,
              type: 'file',
              rawKeyword: itemKeyword,
              triggerType,
              triggers: [itemTrigger],
              caption: caption.trim() || undefined,
              telegramFileId,
              uploadedFileId,
              fileType: entry.type,
              fileName: entry.name,
              fileSize: entry.size,
              buttonText: buttonText.trim() || undefined,
              replyMessage: caption.trim() || undefined,
              retentionType,
              retentionDays: retentionType === 'temporary' ? retentionDays : undefined
            });
          }
        } else {
          // Link Item
          await api.createItem({
            id: autoGeneratedId,
            name: name.trim(),
            type: 'link',
            rawKeyword: cleanKeyword,
            triggerType,
            triggers: [primaryTrigger],
            url: url.trim(),
            openMode,
            buttonText: buttonText.trim() || (openMode === 'webapp' ? '📱 Launch App' : '🌐 Open Link'),
            replyMessage: caption.trim() || `🔗 Here is your requested link: ${url.trim()}`,
            retentionType,
            retentionDays: retentionType === 'temporary' ? retentionDays : undefined
          });
        }
      }

      setModalMode('none');
      onRefresh();
    } catch (err: any) {
      setError(err.message || 'Failed to save item');
    } finally {
      setLoading(false);
      setUploadStatus(null);
    }
  };

  const handleDelete = async (id: string) => {
    setLoading(true);
    try {
      await api.deleteItem(id);
      setDeleteConfirmId(null);
      onRefresh();
    } catch (err: any) {
      alert(err.message || 'Failed to delete');
    } finally {
      setLoading(false);
    }
  };

  const filteredItems = useMemo(() => {
    return items.filter((item) => {
      if (filter === 'file' && item.type !== 'file') return false;
      if (filter === 'link' && item.type !== 'link') return false;
      if (filter === 'temporary' && (item.type !== 'file' || item.retentionType !== 'temporary')) return false;
      if (filter === 'permanent' && (item.type !== 'file' || item.retentionType === 'temporary')) return false;
      if (!search.trim()) return true;
      const q = search.toLowerCase();
      return (
        item.name.toLowerCase().includes(q) ||
        item.rawKeyword.toLowerCase().includes(q) ||
        item.triggers.some((t) => t.toLowerCase().includes(q))
      );
    });
  }, [items, filter, search]);

  return (
    <div className="space-y-4 pb-28">
      {/* Search and Unified Add Button */}
      <div className="flex items-center gap-2">
        <div className="relative flex-1">
          <Search className="absolute left-3 top-1/2 -translate-y-1/2 w-4 h-4 text-zinc-400" />
          <input
            type="text"
            value={search}
            onChange={(e) => setSearch(e.target.value)}
            placeholder="Search files, links, triggers..."
            className="w-full bg-zinc-900/90 border border-zinc-800 rounded-xl py-2 pl-9 pr-3 text-xs text-white placeholder:text-zinc-500 focus:outline-none focus:border-red-500 focus:ring-1 focus:ring-red-500/40 transition-colors"
          />
        </div>

        {/* Add File / Link Action */}
        {(canAddFile || canAddLink) && (
          <button
            onClick={() => openAddModal('file')}
            className="py-2 px-3.5 rounded-xl bg-gradient-to-r from-red-600 via-rose-600 to-red-500 hover:from-red-500 hover:to-rose-500 text-white shadow-[0_0_15px_rgba(239,68,68,0.4)] text-xs font-semibold flex items-center gap-1.5 cursor-pointer active:scale-95 transition-all shrink-0"
          >
            <Plus className="w-3.5 h-3.5" />
            <span>Add File/Link</span>
          </button>
        )}
      </div>

      {/* Segmented Filter */}
      <div className="flex p-1 bg-zinc-900/90 border border-zinc-800/80 rounded-xl text-xs flex-wrap gap-1">
        <button
          onClick={() => setFilter('all')}
          className={`flex-1 min-w-[55px] py-1.5 text-center font-medium rounded-lg transition-colors cursor-pointer ${
            filter === 'all' ? 'bg-zinc-800 text-white shadow-xs' : 'text-zinc-400 hover:text-zinc-200'
          }`}
        >
          All ({items.length})
        </button>
        <button
          onClick={() => setFilter('file')}
          className={`flex-1 min-w-[55px] py-1.5 text-center font-medium rounded-lg transition-colors cursor-pointer ${
            filter === 'file' ? 'bg-red-500/20 text-sky-300 shadow-xs' : 'text-zinc-400 hover:text-zinc-200'
          }`}
        >
          Files ({items.filter((i) => i.type === 'file').length})
        </button>
        <button
          onClick={() => setFilter('temporary')}
          className={`flex-1 min-w-[80px] py-1.5 text-center font-medium rounded-lg transition-colors cursor-pointer ${
            filter === 'temporary' ? 'bg-amber-500/20 text-amber-300 shadow-xs font-semibold' : 'text-zinc-400 hover:text-zinc-200'
          }`}
        >
          ⏳ Temporary ({items.filter((i) => i.type === 'file' && i.retentionType === 'temporary').length})
        </button>
        <button
          onClick={() => setFilter('permanent')}
          className={`flex-1 min-w-[80px] py-1.5 text-center font-medium rounded-lg transition-colors cursor-pointer ${
            filter === 'permanent' ? 'bg-emerald-500/20 text-emerald-300 shadow-xs font-semibold' : 'text-zinc-400 hover:text-zinc-200'
          }`}
        >
          ♾️ Permanent ({items.filter((i) => i.type === 'file' && i.retentionType !== 'temporary').length})
        </button>
        <button
          onClick={() => setFilter('link')}
          className={`flex-1 min-w-[55px] py-1.5 text-center font-medium rounded-lg transition-colors cursor-pointer ${
            filter === 'link' ? 'bg-indigo-500/20 text-indigo-300 shadow-xs' : 'text-zinc-400 hover:text-zinc-200'
          }`}
        >
          Links ({items.filter((i) => i.type === 'link').length})
        </button>
      </div>

      {/* Items List */}
      <div className="space-y-3">
        {filteredItems.length === 0 ? (
          <div className="glass-panel rounded-2xl p-8 text-center border border-zinc-800 text-zinc-400 text-xs">
            No matching items found.
          </div>
        ) : (
          filteredItems.map((item) => {
            const primaryTrigger = item.triggers?.[0] || `#${item.rawKeyword}`;
            const cleanBot = (botUsername || 'AKATSUKISHBOT').replace(/^@/, '');
            const payload = item.id.startsWith('f_') || item.id.startsWith('l_')
              ? item.id
              : `${item.type === 'file' ? 'f_' : 'l_'}${item.id}`;
            const deepLink = `https://t.me/${cleanBot}?start=${payload}`;
            const isCopied = copiedLinkItemId === item.id;

            return (
              <div
                key={item.id}
                className="glass-panel rounded-2xl p-4 border border-zinc-800/80 hover:border-zinc-700/80 transition-all space-y-3 shadow-md"
              >
                {/* Header Row */}
                <div className="flex items-start justify-between gap-3">
                  <div className="flex items-start gap-3 min-w-0">
                    <div
                      className={`w-10 h-10 rounded-xl flex items-center justify-center shrink-0 mt-0.5 ${
                        item.type === 'file'
                          ? 'bg-red-500/10 text-red-400'
                          : 'bg-indigo-500/10 text-indigo-400'
                      }`}
                    >
                      {item.type === 'file' ? <FileText className="w-5 h-5" /> : <Link2 className="w-5 h-5" />}
                    </div>
                    <div className="min-w-0">
                      <div className="text-sm font-semibold text-white truncate">{item.name}</div>
                      
                      {/* Typographic metadata */}
                      <div className="flex items-center gap-1.5 text-xs text-zinc-400 mt-1 flex-wrap">
                        <button
                          type="button"
                          onClick={(e) => {
                            e.stopPropagation();
                            copySingleTag(primaryTrigger);
                          }}
                          title={`Click to copy ${primaryTrigger}`}
                          className="font-mono text-red-400 hover:text-sky-300 font-semibold flex items-center gap-1 cursor-pointer transition-colors group"
                        >
                          <span>{primaryTrigger}</span>
                          {copiedTag === primaryTrigger ? (
                            <Check className="w-3 h-3 text-emerald-400" />
                          ) : (
                            <Copy className="w-3 h-3 text-zinc-500 group-hover:text-red-400 opacity-60 group-hover:opacity-100" />
                          )}
                        </button>
                        <span>·</span>
                        <span className="capitalize">{item.triggerType} trigger</span>
                        <span>·</span>
                        <span>{item.deliveryCount || 0} deliveries</span>
                      </div>
                    </div>
                  </div>
                </div>

                {/* Content details snippet */}
                {item.type === 'file' && (
                  <div className="p-2.5 rounded-xl bg-zinc-900/80 border border-zinc-800/80 text-xs text-zinc-300 space-y-1.5">
                    <div className="flex items-center justify-between text-[11px] text-zinc-400">
                      <span>File: {item.fileName || 'Telegram Media'}</span>
                      <span className="font-mono text-[10px] bg-zinc-950 px-1.5 py-0.5 rounded border border-zinc-800 text-zinc-400">
                        ID: {item.id}
                      </span>
                    </div>

                    {/* Retention Status Badge */}
                    <div className="flex items-center gap-2 pt-0.5">
                      {item.retentionType === 'temporary' ? (
                        (() => {
                          const expiresMs = item.expiresAt ? new Date(item.expiresAt).getTime() : 0;
                          const remainingMs = expiresMs - Date.now();
                          const remainingDays = Math.max(0, Math.ceil(remainingMs / (24 * 60 * 60 * 1000)));
                          const isExpired = remainingMs <= 0;

                          return (
                            <div className={`inline-flex items-center gap-1.5 px-2 py-0.5 rounded-lg text-[11px] font-medium border ${
                              isExpired 
                                ? 'bg-rose-500/10 text-rose-300 border-rose-500/30' 
                                : 'bg-amber-500/10 text-amber-300 border-amber-500/30'
                            }`}>
                              <Clock className="w-3.5 h-3.5 text-amber-400" />
                              <span>
                                {isExpired ? 'Expired (Auto-delete queued)' : `Temporary (${remainingDays}d left)`}
                              </span>
                            </div>
                          );
                        })()
                      ) : (
                        <div className="inline-flex items-center gap-1.5 px-2 py-0.5 rounded-lg text-[11px] font-medium bg-emerald-500/10 text-emerald-300 border border-emerald-500/30">
                          <span className="text-xs">♾️</span>
                          <span>Permanent</span>
                        </div>
                      )}
                    </div>

                    {item.caption && (
                      <div className="text-zinc-300 italic pt-0.5 text-[11px]">"{item.caption}"</div>
                    )}
                  </div>
                )}

                {item.type === 'link' && (
                  <div className="p-2.5 rounded-xl bg-zinc-900/80 border border-zinc-800/80 text-xs text-zinc-300 space-y-1.5">
                    <div className="flex items-center justify-between text-[11px] text-zinc-400">
                      <span className="truncate max-w-[220px] text-zinc-300 font-mono">{item.url}</span>
                      <span className="font-mono text-[10px] bg-zinc-950 px-1.5 py-0.5 rounded border border-zinc-800 text-zinc-400">
                        ID: {item.id}
                      </span>
                    </div>
                    <div className="flex items-center justify-between text-[11px]">
                      <span className="text-indigo-400 font-medium">
                        {item.openMode === 'webapp' ? '📱 Telegram Mini App' : '🌐 Normal Browser'}
                      </span>
                      <span className="text-zinc-400">
                        Button: <strong className="text-white">{item.buttonText || 'Open Link'}</strong>
                      </span>
                    </div>
                  </div>
                )}

                {/* INLINE QUICK ACTIONS ON STORED FILES/LINKS LIST */}
                {/* User Spec: Place quick-action options directly underneath each saved file/link card in the list view: [ Edit ] [ Delete ] [ Generated Link ] */}
                <div className="pt-2.5 border-t border-zinc-800/80 grid grid-cols-3 gap-1.5 sm:gap-2">
                  {/* Quick Option 1: Edit */}
                  <button
                    type="button"
                    onClick={() => openEditModal(item)}
                    className="py-2 px-2 rounded-xl bg-zinc-900 hover:bg-zinc-800 text-zinc-200 hover:text-white border border-zinc-800 hover:border-red-500/30 text-xs font-semibold flex items-center justify-center gap-1.5 transition-all cursor-pointer active:scale-95 shadow-xs"
                  >
                    <Edit2 className="w-3.5 h-3.5 text-red-400 shrink-0" />
                    <span>Edit</span>
                  </button>

                  {/* Quick Option 2: Delete */}
                  <button
                    type="button"
                    onClick={() => setDeleteConfirmId(item.id)}
                    className="py-2 px-2 rounded-xl bg-zinc-900 hover:bg-rose-950/40 text-zinc-300 hover:text-rose-400 border border-zinc-800 hover:border-rose-500/30 text-xs font-semibold flex items-center justify-center gap-1.5 transition-all cursor-pointer active:scale-95 shadow-xs"
                  >
                    <Trash2 className="w-3.5 h-3.5 text-rose-400 shrink-0" />
                    <span>Delete</span>
                  </button>

                  {/* Quick Option 3: Generated Link */}
                  <button
                    type="button"
                    onClick={() => copyDeepLink(item.id, deepLink)}
                    title={deepLink}
                    className={`py-2 px-2 rounded-xl border text-xs font-semibold flex items-center justify-center gap-1.5 transition-all cursor-pointer active:scale-95 shadow-xs truncate ${
                      isCopied
                        ? 'bg-emerald-500/20 text-emerald-300 border-emerald-500/40 shadow-xs'
                        : 'bg-indigo-950/40 hover:bg-indigo-900/60 text-indigo-300 border-indigo-500/30'
                    }`}
                  >
                    {isCopied ? (
                      <>
                        <Check className="w-3.5 h-3.5 text-emerald-400 shrink-0" />
                        <span className="truncate">Copied!</span>
                      </>
                    ) : (
                      <>
                        <Share2 className="w-3.5 h-3.5 text-indigo-400 shrink-0" />
                        <span className="truncate">Generated Link</span>
                      </>
                    )}
                  </button>
                </div>
              </div>
            );
          })
        )}
      </div>

      {/* Delete Confirmation Modal */}
      {deleteConfirmId && (
        <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/70 backdrop-blur-sm">
          <div className="glass-panel w-full max-w-xs rounded-3xl p-5 border border-zinc-700 shadow-2xl">
            <h4 className="font-semibold text-white text-sm mb-1">Delete this item?</h4>
            <p className="text-xs text-zinc-400 mb-4">
              This will permanently remove the item, trigger mappings, and metadata.
            </p>
            <div className="flex gap-2">
              <button
                onClick={() => setDeleteConfirmId(null)}
                className="flex-1 py-2 rounded-xl bg-zinc-800 hover:bg-zinc-700 text-zinc-300 text-xs font-medium cursor-pointer"
              >
                Cancel
              </button>
              <button
                onClick={() => handleDelete(deleteConfirmId)}
                disabled={loading}
                className="flex-1 py-2 rounded-xl bg-rose-500 hover:bg-rose-600 text-white text-xs font-medium cursor-pointer disabled:opacity-50"
              >
                {loading ? 'Deleting...' : 'Delete'}
              </button>
            </div>
          </div>
        </div>
      )}

      {/* REDESIGNED STREAMLINED ADD / EDIT FORM MODAL */}
      {modalMode !== 'none' && (
        <div className="fixed inset-0 z-50 flex items-end sm:items-center justify-center p-0 sm:p-4 bg-black/80 backdrop-blur-md">
          <div className="glass-panel w-full sm:max-w-md max-h-[92vh] overflow-y-auto rounded-t-3xl sm:rounded-3xl p-6 border border-zinc-700 shadow-2xl space-y-4 animate-in slide-in-from-bottom sm:zoom-in-95 duration-200">
            {/* Modal Header */}
            <div className="flex items-center justify-between pb-3 border-b border-zinc-800">
              <div>
                <h3 className="font-bold text-white text-base">
                  {modalMode === 'edit' ? 'Edit Stored Item' : 'Add New File / Link'}
                </h3>
                <div className="flex items-center gap-2 mt-0.5 text-[11px] text-zinc-400">
                  <span className="font-mono text-red-400 font-semibold">ID: {autoGeneratedId}</span>
                  <span className="text-zinc-600">•</span>
                  <span>Auto-Generated</span>
                </div>
              </div>
              <button
                onClick={() => setModalMode('none')}
                className="p-1 rounded-lg text-zinc-400 hover:text-white cursor-pointer"
              >
                <X className="w-5 h-5" />
              </button>
            </div>

            {error && (
              <div className="p-3 rounded-xl bg-rose-500/10 border border-rose-500/25 text-rose-300 text-xs flex items-center gap-2">
                <AlertTriangle className="w-4 h-4 shrink-0 text-rose-400" />
                <span>{error}</span>
              </div>
            )}

            {/* Type Switcher for Add Mode (File vs Link) */}
            {modalMode === 'add' && (
              <div className="grid grid-cols-2 gap-2 p-1 bg-zinc-900 border border-zinc-800 rounded-xl">
                <button
                  type="button"
                  onClick={() => {
                    setItemType('file');
                    setAutoGeneratedId(generateRandomId('file'));
                    setButtonText('📥 Download File');
                    setCaption('Here is your requested file!');
                  }}
                  className={`py-2 rounded-lg text-xs font-semibold flex items-center justify-center gap-1.5 transition-all cursor-pointer ${
                    itemType === 'file'
                      ? 'bg-red-500/20 text-sky-300 border border-red-500/40 shadow-xs'
                      : 'text-zinc-400 hover:text-white'
                  }`}
                >
                  <FileText className="w-3.5 h-3.5" />
                  <span>File / Document</span>
                </button>

                <button
                  type="button"
                  onClick={() => {
                    setItemType('link');
                    setAutoGeneratedId(generateRandomId('link'));
                    setButtonText('🌐 Open Link');
                    setCaption('🔗 Here is your requested link:');
                  }}
                  className={`py-2 rounded-lg text-xs font-semibold flex items-center justify-center gap-1.5 transition-all cursor-pointer ${
                    itemType === 'link'
                      ? 'bg-indigo-500/20 text-indigo-300 border border-indigo-500/40 shadow-xs'
                      : 'text-zinc-400 hover:text-white'
                  }`}
                >
                  <Link2 className="w-3.5 h-3.5" />
                  <span>Web Link</span>
                </button>
              </div>
            )}

            <form onSubmit={handleSave} className="space-y-4">
              {/* 1. File / Link Name field */}
              <div>
                <label className="block text-xs font-semibold text-zinc-300 mb-1">
                  {itemType === 'file' ? 'File Name *' : 'Link Title / Name *'}
                </label>
                <input
                  type="text"
                  required
                  value={name}
                  onChange={(e) => setName(e.target.value)}
                  placeholder={itemType === 'file' ? 'e.g. Free Fire Mod APK' : 'e.g. Official Community Link'}
                  className="w-full bg-zinc-900 border border-zinc-700 rounded-xl py-2 px-3 text-sm text-white focus:outline-none focus:border-red-500 focus:ring-1 focus:ring-red-500/40 transition-colors"
                />
              </div>

              {/* 2. File Trigger field & Trigger Type Selection */}
              <div>
                <div className="flex items-center justify-between mb-1.5">
                  <label className="text-xs font-semibold text-zinc-300">
                    File Trigger *
                  </label>
                  <span className="text-xs font-mono text-red-400 font-bold">
                    Active: {previewTrigger()}
                  </span>
                </div>

                {/* Trigger Type Toggle */}
                <div className="grid grid-cols-3 gap-1.5 mb-2">
                  <button
                    type="button"
                    onClick={() => setTriggerType('hashtag')}
                    className={`py-1.5 px-2 rounded-lg text-xs font-medium border text-center transition-all cursor-pointer ${
                      triggerType === 'hashtag'
                        ? 'bg-red-500/20 border-red-500 text-sky-300 font-semibold'
                        : 'bg-zinc-900 border-zinc-700 text-zinc-400 hover:text-white'
                    }`}
                  >
                    # Hashtag
                  </button>
                  <button
                    type="button"
                    onClick={() => setTriggerType('slash')}
                    className={`py-1.5 px-2 rounded-lg text-xs font-medium border text-center transition-all cursor-pointer ${
                      triggerType === 'slash'
                        ? 'bg-red-500/20 border-red-500 text-sky-300 font-semibold'
                        : 'bg-zinc-900 border-zinc-700 text-zinc-400 hover:text-white'
                    }`}
                  >
                    / Slash
                  </button>
                  <button
                    type="button"
                    onClick={() => setTriggerType('normal')}
                    className={`py-1.5 px-2 rounded-lg text-xs font-medium border text-center transition-all cursor-pointer ${
                      triggerType === 'normal'
                        ? 'bg-red-500/20 border-red-500 text-sky-300 font-semibold'
                        : 'bg-zinc-900 border-zinc-700 text-zinc-400 hover:text-white'
                    }`}
                  >
                    🔤 Normal
                  </button>
                </div>

                <input
                  type="text"
                  required
                  value={rawKeyword}
                  onChange={(e) => setRawKeyword(e.target.value)}
                  placeholder="e.g. ff (without prefix)"
                  className="w-full bg-zinc-900 border border-zinc-700 rounded-xl py-2 px-3 text-sm text-white font-mono focus:outline-none focus:border-red-500 focus:ring-1 focus:ring-red-500/40 transition-colors"
                />
              </div>

              {/* 3. Upload from Gallery with Multi-File support */}
              {itemType === 'file' && (
                <div className="p-3.5 rounded-2xl bg-gradient-to-b from-zinc-900 via-zinc-900 to-zinc-950 border border-zinc-700/80 space-y-3">
                  <div className="flex items-center justify-between">
                    <label className="text-xs font-bold text-white flex items-center gap-1.5">
                      <Upload className="w-4 h-4 text-red-400" />
                      <span>Upload from Gallery / Files</span>
                    </label>
                    <span className="text-[10px] text-sky-300 bg-sky-950/60 border border-red-500/30 px-2 py-0.5 rounded-full font-semibold">
                      Multi-File Supported
                    </span>
                  </div>

                  <p className="text-[11px] text-zinc-400">
                    Select one or multiple files (Photos, Videos, APK, ZIP, Documents).
                  </p>

                  <label className="w-full py-3 px-4 rounded-xl border border-dashed border-red-500/40 hover:border-sky-400 bg-red-500/10 hover:bg-red-500/15 flex flex-col items-center justify-center gap-1 cursor-pointer transition-all">
                    <Paperclip className="w-5 h-5 text-red-400" />
                    <span className="text-xs font-semibold text-white">
                      Browse &amp; Select Multiple Files
                    </span>
                    <span className="text-[10px] text-zinc-400">
                      Tap to select from Gallery or Storage
                    </span>
                    <input
                      type="file"
                      multiple
                      className="hidden"
                      onChange={handleMultiFileSelect}
                    />
                  </label>

                  {/* Selected Files Preview List with (X) Remove icon on each */}
                  {selectedFiles.length > 0 && (
                    <div className="space-y-1.5 pt-1">
                      <div className="text-[11px] font-semibold text-zinc-300 flex items-center justify-between">
                        <span>Selected Files ({selectedFiles.length}):</span>
                        <button
                          type="button"
                          onClick={() => setSelectedFiles([])}
                          className="text-[10px] text-rose-400 hover:underline cursor-pointer"
                        >
                          Clear All
                        </button>
                      </div>

                      <div className="max-h-36 overflow-y-auto space-y-1 pr-1">
                        {selectedFiles.map((f) => (
                          <div
                            key={f.id}
                            className="flex items-center justify-between p-2 rounded-xl bg-zinc-950/90 border border-zinc-800 text-xs group hover:border-zinc-700 transition-colors"
                          >
                            <div className="flex items-center gap-2 min-w-0 pr-2">
                              {f.previewUrl ? (
                                <img
                                  src={f.previewUrl}
                                  alt={f.name}
                                  className="w-7 h-7 rounded object-cover shrink-0"
                                />
                              ) : f.type === 'video' ? (
                                <Video className="w-4 h-4 text-purple-400 shrink-0" />
                              ) : f.type === 'audio' ? (
                                <Music className="w-4 h-4 text-emerald-400 shrink-0" />
                              ) : (
                                <FileText className="w-4 h-4 text-red-400 shrink-0" />
                              )}
                              <div className="min-w-0">
                                <div className="text-xs font-medium text-white truncate max-w-[200px]">
                                  {f.name}
                                </div>
                                <div className="text-[10px] text-zinc-500">
                                  {(f.size / (1024 * 1024)).toFixed(2)} MB · {f.type}
                                </div>
                              </div>
                            </div>

                            {/* Small Cross (X) icon on its side to easily remove individual files before saving */}
                            <button
                              type="button"
                              onClick={() => handleRemoveFile(f.id)}
                              title={`Remove ${f.name}`}
                              className="w-6 h-6 rounded-lg bg-zinc-800 hover:bg-rose-500/20 text-zinc-400 hover:text-rose-400 flex items-center justify-center transition-colors cursor-pointer shrink-0"
                            >
                              <X className="w-3.5 h-3.5" />
                            </button>
                          </div>
                        ))}
                      </div>
                    </div>
                  )}

                  {uploadStatus && (
                    <div className="text-[11px] text-red-400 font-mono flex items-center gap-1.5 pt-1">
                      <Loader2 className="w-3.5 h-3.5 animate-spin" />
                      <span>{uploadStatus}</span>
                    </div>
                  )}
                </div>
              )}

              {/* Link Target URL field */}
              {itemType === 'link' && (
                <div className="space-y-3">
                  <div>
                    <label className="block text-xs font-semibold text-zinc-300 mb-1">Target URL *</label>
                    <input
                      type="url"
                      required
                      value={url}
                      onChange={(e) => setUrl(e.target.value)}
                      placeholder="https://example.com"
                      className="w-full bg-zinc-900 border border-zinc-700 rounded-xl py-2 px-3 text-sm text-white focus:outline-none focus:border-red-500 focus:ring-1 focus:ring-red-500/40"
                    />
                  </div>

                  <div>
                    <label className="block text-xs font-semibold text-zinc-300 mb-1.5">Open Mode *</label>
                    <div className="grid grid-cols-2 gap-2">
                      <button
                        type="button"
                        onClick={() => setOpenMode('browser')}
                        className={`p-2.5 rounded-xl border text-left transition-all cursor-pointer ${
                          openMode === 'browser'
                            ? 'bg-indigo-500/20 border-indigo-500 text-indigo-300'
                            : 'bg-zinc-900 border-zinc-700 text-zinc-400'
                        }`}
                      >
                        <Globe className="w-4 h-4 mb-1 text-indigo-400" />
                        <div className="text-xs font-semibold text-white">Web Browser</div>
                        <div className="text-[10px] text-zinc-400">External browser</div>
                      </button>

                      <button
                        type="button"
                        onClick={() => setOpenMode('webapp')}
                        className={`p-2.5 rounded-xl border text-left transition-all cursor-pointer ${
                          openMode === 'webapp'
                            ? 'bg-red-500/20 border-red-500 text-sky-300'
                            : 'bg-zinc-900 border-zinc-700 text-zinc-400'
                        }`}
                      >
                        <Smartphone className="w-4 h-4 mb-1 text-red-400" />
                        <div className="text-xs font-semibold text-white">Telegram Mini App</div>
                        <div className="text-[10px] text-zinc-400">Embedded view</div>
                      </button>
                    </div>
                  </div>
                </div>
              )}

              {/* 4. Private Delivery Message & Inline Button Text (Pre-filled with default texts, fully editable) */}
              <div className="grid grid-cols-1 gap-3 pt-1">
                <div>
                  <label className="block text-xs font-semibold text-zinc-300 mb-1">
                    Private Delivery Message
                  </label>
                  <textarea
                    rows={2}
                    value={caption}
                    onChange={(e) => setCaption(e.target.value)}
                    placeholder="Message sent in private DM when user triggers this item"
                    className="w-full bg-zinc-900 border border-zinc-700 rounded-xl p-2.5 text-xs text-white focus:outline-none focus:border-red-500 focus:ring-1 focus:ring-red-500/40"
                  />
                </div>

                <div>
                  <label className="block text-xs font-semibold text-zinc-300 mb-1">
                    Inline Button Text
                  </label>
                  <input
                    type="text"
                    value={buttonText}
                    onChange={(e) => setButtonText(e.target.value)}
                    placeholder="e.g. 📥 Download File or 🌐 Open Link"
                    className="w-full bg-zinc-900 border border-zinc-700 rounded-xl py-2 px-3 text-xs text-white focus:outline-none focus:border-red-500 focus:ring-1 focus:ring-red-500/40"
                  />
                </div>
              </div>

              {/* Auto-generated File ID / Link ID */}
              <div>
                <div className="flex items-center justify-between mb-1">
                  <label className="text-xs font-semibold text-zinc-300">
                    {itemType === 'file' ? 'Auto-generated File ID' : 'Auto-generated Link ID'}
                  </label>
                  <span className="text-[10px] text-zinc-500">Auto-assigned identifier</span>
                </div>
                <div className="flex items-center gap-2">
                  <input
                    type="text"
                    readOnly
                    value={autoGeneratedId}
                    className="w-full bg-zinc-950 border border-zinc-800 rounded-xl py-2 px-3 text-xs text-red-400 font-mono font-semibold focus:outline-none select-all cursor-default"
                  />
                  <button
                    type="button"
                    onClick={() => {
                      navigator.clipboard.writeText(autoGeneratedId);
                      setCopiedTag(autoGeneratedId);
                      setTimeout(() => setCopiedTag((p) => (p === autoGeneratedId ? null : p)), 1800);
                    }}
                    title="Copy ID"
                    className="p-2 rounded-xl bg-zinc-900 border border-zinc-700/80 hover:bg-zinc-800 text-zinc-300 hover:text-white transition-colors cursor-pointer shrink-0"
                  >
                    {copiedTag === autoGeneratedId ? (
                      <Check className="w-4 h-4 text-emerald-400" />
                    ) : (
                      <Copy className="w-4 h-4 text-zinc-400" />
                    )}
                  </button>
                </div>
              </div>

              {/* 5. Permanent vs. Temporary Storage Toggle with expiration days */}
              <div className="p-3.5 rounded-2xl bg-gradient-to-b from-zinc-900 to-zinc-950 border border-zinc-700/80 space-y-3">
                <div className="flex items-center justify-between">
                  <label className="text-xs font-bold text-white flex items-center gap-1.5">
                    <Clock className="w-4 h-4 text-amber-400" />
                    <span>Storage Duration</span>
                  </label>
                  <span className={`text-[10px] px-2 py-0.5 rounded-md font-semibold border ${
                    retentionType === 'temporary'
                      ? 'bg-amber-500/20 text-amber-300 border-amber-500/40'
                      : 'bg-emerald-500/20 text-emerald-300 border-emerald-500/40'
                  }`}>
                    {retentionType === 'temporary' ? '⏳ Temporary' : '♾️ Permanent'}
                  </span>
                </div>

                <div className="grid grid-cols-2 gap-2">
                  <button
                    type="button"
                    onClick={() => setRetentionType('permanent')}
                    className={`p-2.5 rounded-xl border text-left transition-all cursor-pointer ${
                      retentionType === 'permanent'
                        ? 'bg-emerald-500/15 border-emerald-500 text-emerald-300 ring-1 ring-emerald-500/40'
                        : 'bg-zinc-900/90 border-zinc-800 text-zinc-400 hover:text-white'
                    }`}
                  >
                    <div className="flex items-center gap-1.5 font-semibold text-xs text-white">
                      <span>♾️</span>
                      <span>Permanent</span>
                    </div>
                    <div className="text-[10px] text-zinc-400 mt-0.5">
                      Never deleted automatically
                    </div>
                  </button>

                  <button
                    type="button"
                    onClick={() => setRetentionType('temporary')}
                    className={`p-2.5 rounded-xl border text-left transition-all cursor-pointer ${
                      retentionType === 'temporary'
                        ? 'bg-amber-500/15 border-amber-500 text-amber-300 ring-1 ring-amber-500/40'
                        : 'bg-zinc-900/90 border-zinc-800 text-zinc-400 hover:text-white'
                    }`}
                  >
                    <div className="flex items-center gap-1.5 font-semibold text-xs text-white">
                      <span>⏳</span>
                      <span>Temporary</span>
                    </div>
                    <div className="text-[10px] text-zinc-400 mt-0.5">
                      Auto-delete after set days
                    </div>
                  </button>
                </div>

                {/* Expiration Days option */}
                {retentionType === 'temporary' && (
                  <div className="pt-2 border-t border-zinc-800/80 space-y-2.5 animate-in fade-in duration-150">
                    <div className="flex items-center justify-between">
                      <label className="text-xs font-semibold text-amber-300">
                        Expiration Duration (Days)
                      </label>
                      <span className="text-[11px] text-zinc-400">
                        {retentionDays} Days
                      </span>
                    </div>

                    <div className="flex items-center gap-2">
                      <input
                        type="number"
                        min="1"
                        max="3650"
                        value={retentionDays}
                        onChange={(e) => {
                          const val = Math.max(1, parseInt(e.target.value, 10) || 1);
                          setRetentionDays(val);
                        }}
                        className="w-20 bg-zinc-950 border border-amber-500/40 rounded-xl py-1.5 px-3 text-sm text-white font-mono font-bold focus:outline-none focus:border-amber-400"
                      />
                      <span className="text-xs text-zinc-400">Days</span>

                      {/* Quick day presets */}
                      <div className="flex items-center gap-1 flex-wrap">
                        {[1, 3, 7, 15, 30].map((d) => (
                          <button
                            key={d}
                            type="button"
                            onClick={() => setRetentionDays(d)}
                            className={`px-2 py-1 rounded-lg text-[10px] font-semibold border transition-all cursor-pointer ${
                              retentionDays === d
                                ? 'bg-amber-500 text-zinc-950 border-amber-400 font-bold'
                                : 'bg-zinc-800 hover:bg-zinc-700 text-zinc-300 border-zinc-700'
                            }`}
                          >
                            {d}d
                          </button>
                        ))}
                      </div>
                    </div>

                    <div className="p-2 rounded-xl bg-amber-500/10 border border-amber-500/25 text-[11px] text-amber-200 flex items-center gap-2">
                      <Calendar className="w-3.5 h-3.5 text-amber-400 shrink-0" />
                      <span>
                        Expires: <strong className="text-white">{new Date(Date.now() + (retentionDays || 1) * 86400000).toLocaleDateString('en-US', { day: 'numeric', month: 'short', year: 'numeric' })}</strong>
                      </span>
                    </div>
                  </div>
                )}
              </div>

              {/* Form Action Buttons */}
              <div className="flex gap-2 pt-2">
                <button
                  type="button"
                  onClick={() => setModalMode('none')}
                  className="flex-1 py-2.5 rounded-xl bg-zinc-800 hover:bg-zinc-700 text-zinc-300 text-xs font-semibold cursor-pointer transition-colors"
                >
                  Cancel
                </button>
                <button
                  type="submit"
                  disabled={loading || uploading}
                  className="flex-1 py-2.5 rounded-xl bg-gradient-to-r from-red-600 via-rose-600 to-red-500 hover:brightness-110 text-white text-xs font-semibold shadow-[0_0_20px_rgba(239,68,68,0.4)] cursor-pointer disabled:opacity-50 transition-all flex items-center justify-center gap-1.5"
                >
                  {loading ? (
                    <>
                      <Loader2 className="w-3.5 h-3.5 animate-spin" />
                      <span>Saving...</span>
                    </>
                  ) : (
                    <>
                      <Check className="w-3.5 h-3.5" />
                      <span>{modalMode === 'edit' ? 'Update Item' : 'Save Item'}</span>
                    </>
                  )}
                </button>
              </div>
            </form>
          </div>
        </div>
      )}
    </div>
  );
};

export const FilesTab = React.memo(FilesTabComponent);
